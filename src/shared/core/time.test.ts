import { describe, expect, it } from "vitest";
import { osloDay } from "./time";

describe("FR-25 osloDay", () => {
  it.each([
    // Winter (UTC+1): Oslo midnight is 23:00 UTC.
    ["2026-01-15T22:59:59Z", "2026-01-15"],
    ["2026-01-15T23:00:00Z", "2026-01-16"],
    ["2026-01-15T23:59:59Z", "2026-01-16"],
    ["2026-01-16T00:00:00Z", "2026-01-16"],
    // Summer (UTC+2): Oslo midnight is 22:00 UTC.
    ["2026-07-15T21:59:59Z", "2026-07-15"],
    ["2026-07-15T22:00:00Z", "2026-07-16"],
    ["2026-07-15T23:30:00Z", "2026-07-16"],
    // UTC midnight is not Oslo midnight.
    ["2026-07-16T00:00:00Z", "2026-07-16"],
    // Spring forward, 29 March 2026 (01:00 UTC): the day before is still UTC+1.
    ["2026-03-28T22:59:59Z", "2026-03-28"],
    ["2026-03-28T23:00:00Z", "2026-03-29"],
    ["2026-03-29T21:59:59Z", "2026-03-29"],
    ["2026-03-29T22:00:00Z", "2026-03-30"],
    // Fall back, 25 October 2026 (01:00 UTC): that day has 25 hours.
    ["2026-10-24T21:59:59Z", "2026-10-24"],
    ["2026-10-24T22:00:00Z", "2026-10-25"],
    ["2026-10-25T22:59:59Z", "2026-10-25"],
    ["2026-10-25T23:00:00Z", "2026-10-26"],
    // New year.
    ["2026-12-31T22:59:59Z", "2026-12-31"],
    ["2026-12-31T23:00:00Z", "2027-01-01"],
  ])("%s is %s in Oslo", (instant, day) => {
    expect(osloDay(new Date(instant))).toBe(day);
  });
});
